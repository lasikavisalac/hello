import java.util.LinkedList;
public class day102 {
    static void main() {
        LinkedList<String> queue = new LinkedList<String>();
        queue.add("tiger");
        queue.add("lion");
        queue.add("cat");
        queue.add("dog");
        while(!queue.isEmpty()) {
            process(queue);
        }
    }
    static void process(LinkedList<String> queue){
        String removed=queue.removeFirst();
        System.out.println("Removed:"+removed);

    }
}




















































































































































































